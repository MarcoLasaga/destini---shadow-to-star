def get_system_catalog_items(gender: str = "unisex") -> List[Dict[str, Any]]:
    """Filters the system catalog by the user's gender (male, female, or unisex)."""
    norm_gender = (gender or "unisex").strip().lower()
    if norm_gender == "male":
        return [i for i in SYSTEM_DATASET_CATALOG if i.get("target_gender") in ("male", "unisex")]
    elif norm_gender == "female":
        return [i for i in SYSTEM_DATASET_CATALOG if i.get("target_gender") in ("female", "unisex")]
    return list(SYSTEM_DATASET_CATALOG)

